function [root, T] = secant(f, x0, x1, tol, max_iter)
% =========================================================================
% خوارزمية طريقة القاطع (The Secant Method)
% مادة: التحليل العددي (Numerical Analysis)
% =========================================================================
% الوظيفة:
%   طريقة مفتوحة (Open Method) لإيجاد جذور المعادلات غير الخطية f(x) = 0
%   باستخدام نقطتين ابتدائيتين دون الحاجة لحساب المشتقة تحليلياً
%   (حيث تُستبدل المشتقة في قانون نيوتن بميل القاطع المار بالنقطتين).
%
% صيغة التكرار:
%   x_{n+1} = x_n - [ f(x_n) * (x_n - x_{n-1}) ] / [ f(x_n) - f(x_{n-1}) ]
%
% المدخلات (Inputs):
%   f        : دالة رياضية كـ function handle، مثال: @(x) x.^3 - x - 2
%   x0       : التخمين الابتدائي الأول
%   x1       : التخمين الابتدائي الثاني
%   tol      : الدقة المطلوبة (افتراضياً: 1e-4)
%   max_iter : أقصى عدد تكرارات (افتراضياً: 50)
%
% المخرجات (Outputs):
%   root     : القيمة التقريبية للجذر المحسوب
%   T        : جدول التكرارات التفصيلي
% =========================================================================

    if nargin < 1 || isempty(f), f = @(x) x.^3 - x - 2; end
    if nargin < 2 || isempty(x0), x0 = 1.0; end
    if nargin < 3 || isempty(x1), x1 = 2.0; end
    if nargin < 4 || isempty(tol), tol = 1e-4; end
    if nargin < 5 || isempty(max_iter), max_iter = 50; end

    if ischar(f) || isstring(f)
        f = str2func(['@(x) ' char(f)]);
    end

    fprintf('\n=================================================================\n');
    fprintf('  طريقة القاطع لحل المعادلات غير الخطية (Secant Method)\n');
    fprintf('=================================================================\n');
    fprintf('التخمين الابتدائي: x0 = %.4f,  x1 = %.4f\n', x0, x1);
    fprintf('الدقة المطلوبة: %e\n', tol);
    fprintf('-----------------------------------------------------------------\n');

    fprintf('%-4s | %-10s | %-10s | %-10s | %-11s | %-10s\n', ...
        'n', 'x_{n-1}', 'x_n', 'x_{n+1}', 'f(x_{n+1})', 'الخطأ |x_{n+1}-x_n|');
    fprintf('-----------------------------------------------------------------\n');

    table_data = [];

    for n = 1:max_iter
        fx0 = f(x0);
        fx1 = f(x1);

        denom = fx1 - fx0;
        if abs(denom) < 1e-15
            error('خطأ: الفرق بين قيمي الدالتين f(x1) - f(x0) مساوٍ للصفر تقريباً؛ يؤدي لقسمة على صفر.');
        end

        % حساب النقطة التالية x2
        x2 = x1 - (fx1 * (x1 - x0)) / denom;
        fx2 = f(x2);
        err = abs(x2 - x1);

        fprintf('%-4d | %10.5f | %10.5f | %10.5f | %11.5e | %10.5e\n', ...
            n, x0, x1, x2, fx2, err);

        table_data = [table_data; n, x0, x1, x2, fx2, err]; %#ok<AGROW>

        if err < tol || abs(fx2) < 1e-12
            fprintf('-----------------------------------------------------------------\n');
            fprintf('✓ تم الوصول للحل بنجاح عند التكرار n = %d\n', n);
            fprintf('✓ الجذر التقريبي: x ≈ %.6f\n', x2);
            fprintf('✓ قيمة الدالة عند الجذر: f(x) = %e\n', fx2);
            root = x2;
            T = table_data;
            return;
        end

        % إزاحة النقاط للخطوة التالية
        x0 = x1;
        x1 = x2;
    end

    root = x2;
    T = table_data;
    warning('تم بلوغ الحد الأقصى للتكرارات (%d) دون تحقيق شرط التوقف بالكامل.', max_iter);
end
