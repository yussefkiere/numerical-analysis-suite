function [I, T] = trapezoidal_rule(f, a, b, n)
% =========================================================================
% خوارزمية قاعدة شبه المنحرف المركبة (Composite Trapezoidal Rule)
% مادة: التحليل العددي (Numerical Analysis)
% =========================================================================
% الوظيفة:
%   التقريب العددي للتكامل المحدد للدالة f(x) من a إلى b:
%   integral_a^b f(x) dx ≈ (h/2) * [ f(x0) + 2*f(x1) + ... + 2*f(xn-1) + f(xn) ]
%   حيث عرض الشريحة h = (b - a) / n
%
% المدخلات (Inputs):
%   f : دالة التكامل كـ function handle، مثال: @(x) 1 ./ (1 + x.^2)
%   a : الحد الأدنى للتكامل
%   b : الحد الأعلى للتكامل
%   n : عدد الفترات الجزئية (الشرائح)
%
% المخرجات (Outputs):
%   I : القيمة التقريبية للتكامل
%   T : جدول إحداثيات النقاط x_i وقيم الدوال وأوزان شبه المنحرف
% =========================================================================

    if nargin < 1 || isempty(f), f = @(x) 1 ./ (1 + x.^2); end
    if nargin < 2 || isempty(a), a = 0.0; end
    if nargin < 3 || isempty(b), b = 1.0; end
    if nargin < 4 || isempty(n), n = 4; end

    if ischar(f) || isstring(f), f = str2func(['@(x) ' char(f)]); end

    if a >= b
        error('خطأ: يجب أن يكون الحد الأدنى للتكامل a أصغر من الحد الأعلى b.');
    end
    if n <= 0 || mod(n, 1) ~= 0
        error('خطأ: عدد الفترات n يجب أن يكون عدداً صحيحاً موجباً.');
    end

    h = (b - a) / n;
    x = linspace(a, b, n + 1);
    y = f(x);

    % الأوزان: 1 للطرفين، و 2 للنقاط الداخلية
    weights = ones(1, n + 1);
    weights(2:end-1) = 2;

    I = (h / 2) * sum(weights .* y);

    fprintf('\n=================================================================\n');
    fprintf('  قاعدة شبه المنحرف المركبة للتكامل العددي (Trapezoidal Rule)\n');
    fprintf('=================================================================\n');
    fprintf('حدود التكامل: [%.4f, %.4f],  عدد الشرائح n = %d,  عرض الشريحة h = %.4f\n', a, b, n, h);
    fprintf('-----------------------------------------------------------------\n');
    fprintf('%-4s | %-10s | %-12s | %-6s | %-12s\n', ...
        'i', 'x_i', 'f(x_i)', 'الوزن', 'المساهمة الجزئية');
    fprintf('-----------------------------------------------------------------\n');

    table_data = [];
    for i = 1:n+1
        contrib = weights(i) * y(i);
        fprintf('%-4d | %10.5f | %12.6f | %-6d | %12.6f\n', ...
            i-1, x(i), y(i), weights(i), contrib);
        table_data = [table_data; i-1, x(i), y(i), weights(i), contrib]; %#ok<AGROW>
    end

    fprintf('-----------------------------------------------------------------\n');
    fprintf('✓ قيمة التكامل المقدرة I ≈ %12.6f\n', I);
    fprintf('=================================================================\n');
    T = table_data;
end
