function x = cramer_rule(A, b)
% =========================================================================
% خوارزمية قاعدة كرامر بالمحددات (Cramer's Rule)
% مادة: التحليل العددي (Numerical Analysis)
% =========================================================================
% الوظيفة:
%   حل نظام المعادلات الخطية A * x = b باستخدام المحددات (Determinants).
%   x_i = det(A_i) / det(A)
%   حيث A_i هي المصفوفة الناتجة عن استبدال العمود i بالمتجه b.
%
% المدخلات (Inputs):
%   A : مصفوفة المعاملات المربعة (n x n)
%   b : متجه الثوابت (n x 1)
%
% المخرجات (Outputs):
%   x : متجه الحل الدقيق للنظام (n x 1)
% =========================================================================

    if nargin < 1 || isempty(A)
        % مثال نموذجي من اختبارات المقرر:
        % x1 + 2x2 +  x3 = 8
        % 2x1 + 3x2 + 4x3 = 20
        % 4x1 + 3x2 + 2x3 = 16
        A = [1, 2, 1; ...
             2, 3, 4; ...
             4, 3, 2];
    end
    if nargin < 2 || isempty(b)
        b = [8; 20; 16];
    end

    b = b(:);
    n = length(b);

    if size(A, 1) ~= size(A, 2) || size(A, 1) ~= n
        error('خطأ: يجب أن تكون مصفوفة المعاملات A مربعة ومتوافقة مع المتجه b.');
    end

    fprintf('\n=================================================================\n');
    fprintf('  طريقة قاعدة كرامر لحل الأنظمة الخطية (Cramer''s Rule)\n');
    fprintf('=================================================================\n');

    % 1. حساب محدد المصفوفة الرئيسية Δ = det(A)
    detA = det(A);
    fprintf('المحدد الرئيسي للنظام: Δ = det(A) = %.6f\n', detA);

    if abs(detA) < 1e-12
        error('خطأ: محدد المصفوفة det(A) يساوي صفراً؛ لا يمكن تطبيق قاعدة كرامر (النظام ليس له حل وحيد).');
    end

    x = zeros(n, 1);
    fprintf('\nخطوات استبدال الأعمدة وحساب المحددات الفرعية:\n');
    fprintf('-----------------------------------------------------------------\n');

    % 2. استبدال كل عمود بالمتجه b وحساب المحدد
    for i = 1:n
        Ai = A;
        Ai(:, i) = b; % استبدال العمود رقم i
        detAi = det(Ai);
        x(i) = detAi / detA;

        fprintf('المتغير x%d:\n', i);
        fprintf('  المصفوفة A_%d بعد استبدال العمود %d بالمتجه b:\n', i, i);
        disp(Ai);
        fprintf('  Δ_%d = det(A_%d) = %10.4f\n', i, i, detAi);
        fprintf('  x%d = Δ_%d / Δ = %.4f / %.4f = %10.6f\n', ...
            i, i, detAi, detA, x(i));
        fprintf('-----------------------------------------------------------------\n');
    end

    fprintf('✓ خلاصة حل النظام بقاعدة كرامر:\n');
    for i = 1:n
        fprintf('  x%d = %10.6f\n', i, x(i));
    end
    fprintf('=================================================================\n');
end
