function [x, Aug] = gauss_elimination(A, b)
% =========================================================================
% خوارزمية طريقة حذف جاوس مع التعويض العكسي (Gaussian Elimination)
% مادة: التحليل العددي (Numerical Analysis)
% =========================================================================
% الوظيفة:
%   حل نظام المعادلات الخطية: A * x = b
%   من خلال تحويل المصفوفة الموسعة [A | b] إلى مصفوفة مثلثية عليا
%   ثم استنتاج المجاهيل بالتعويض العكسي (Back Substitution).
%
% المدخلات (Inputs):
%   A : مصفوفة المعاملات المربعة (n x n)
%   b : متجه الثوابت (n x 1)
%
% المخرجات (Outputs):
%   x   : متجه حل النظام (n x 1)
%   Aug : المصفوفة الموسعة النهائية في الصورة المثلثية العليا
% =========================================================================

    if nargin < 1 || isempty(A)
        % مثال المحاضرة المعتمد:
        % 2x1 + x2 - x3 = -1
        % 3x1 + 5x2 + 2x3 = 2
        % 4x1 - x2 - 2x3 = 1
        A = [2, 1, -1; ...
             3, 5,  2; ...
             4, -1, -2];
    end
    if nargin < 2 || isempty(b)
        b = [-1; 2; 1];
    end

    b = b(:); % التأكد من أنه متجه عمود
    n = length(b);

    if size(A, 1) ~= size(A, 2) || size(A, 1) ~= n
        error('خطأ: يجب أن تكون المصفوفة A مربعة، ومتوافقة الأبعاد مع المتجه b.');
    end

    fprintf('\n=================================================================\n');
    fprintf('  طريقة حذف جاوس لحل الأنظمة الخطية (Gaussian Elimination)\n');
    fprintf('=================================================================\n');
    fprintf('رتبة النظام: %d x %d\n', n, n);

    Aug = [A, b];
    fprintf('\n[1] المصفوفة الموسعة الابتدائية [A | b]:\n');
    disp(Aug);

    % 1. الحذف الأمامي (Forward Elimination) مع التمحور الجزئي (Partial Pivoting)
    for k = 1:n-1
        % اختيار أكبر عنصر في العمود للتمحور لتقليل الخطأ الحسابي
        [max_val, max_row] = max(abs(Aug(k:n, k)));
        max_row = max_row + k - 1;

        if max_val < 1e-12
            error('خطأ: المصفوفة منفردة أو قريبة من الانفراد؛ لا يوجد حل وحيد للنظام.');
        end

        % تبديل الصفوف إذا لزم الأمر
        if max_row ~= k
            Aug([k, max_row], :) = Aug([max_row, k], :);
            fprintf('<- تم تبديل الصف R%d مع R%d لتحقيق التمحور الأمثل.\n', k, max_row);
        end

        % تصفير ما تحت عنصر المحور Aug(k,k)
        for i = k+1:n
            factor = Aug(i, k) / Aug(k, k);
            Aug(i, k:n+1) = Aug(i, k:n+1) - factor * Aug(k, k:n+1);
            fprintf('العملية: R%d = R%d - (%.4f) * R%d\n', i, i, factor, k);
        end

        fprintf('\nالمصفوفة الموسعة بعد الخطوة %d:\n', k);
        disp(Aug);
    end

    % فحص محدد المحور الأخير
    if abs(Aug(n, n)) < 1e-12
        error('خطأ: العنصر القطري الأخير مساوٍ للصفر؛ النظام ليس له حل وحيد.');
    end

    % 2. التعويض العكسي (Back Substitution)
    x = zeros(n, 1);
    x(n) = Aug(n, n+1) / Aug(n, n);
    fprintf('\n[2] خطوات التعويض العكسي (Back Substitution):\n');
    fprintf('x%d = %.4f / %.4f = %.6f\n', n, Aug(n, n+1), Aug(n, n), x(n));

    for i = n-1:-1:1
        sum_terms = Aug(i, i+1:n) * x(i+1:n);
        x(i) = (Aug(i, n+1) - sum_terms) / Aug(i, i);
        fprintf('x%d = (%.4f - %.4f) / %.4f = %.6f\n', ...
            i, Aug(i, n+1), sum_terms, Aug(i, i), x(i));
    end

    fprintf('-----------------------------------------------------------------\n');
    fprintf('✓ تم استخراج حل النظام بنجاح:\n');
    for i = 1:n
        fprintf('  x%d = %10.6f\n', i, x(i));
    end
    fprintf('-----------------------------------------------------------------\n');
end
