function [y_eval, L] = lagrange_interpolation(x_pts, y_pts, x_eval)
% =========================================================================
% خوارزمية استيفاء كثيرات حدود لاجرانج (Lagrange Polynomial Interpolation)
% مادة: التحليل العددي (Numerical Analysis)
% =========================================================================
% الوظيفة:
%   إيجاد قيمة تقريبية للدالة عند نقطة x_eval بالاعتماد على نقاط معلومة
%   P_n(x) = sum_{i=0}^n y_i * L_i(x)
%   حيث دوال الأساس للاجرانج:
%   L_i(x) = prod_{j ~= i} (x - x_j) / (x_i - x_j)
%
% المدخلات (Inputs):
%   x_pts  : متجهات الإحداثيات السينية للنقاط المعطاة [x0, x1, ..., xn]
%   y_pts  : متجهات الإحداثيات الصادية المقابلة لها [y0, y1, ..., yn]
%   x_eval : النقطة المراد تقدير قيمة الدالة عندها
%
% المخرجات (Outputs):
%   y_eval : القيمة المستوفاة P_n(x_eval)
%   L      : قيم دوال الأساس لاجرانج L_i عند النقطة x_eval
% =========================================================================

    if nargin < 1 || isempty(x_pts), x_pts = [1, 2, 3]; end
    if nargin < 2 || isempty(y_pts), y_pts = [1, 4, 9]; end % الدالة f(x) = x^2
    if nargin < 3 || isempty(x_eval), x_eval = 2.5; end

    x_pts = x_pts(:)';
    y_pts = y_pts(:)';
    n = length(x_pts);

    if length(y_pts) ~= n
        error('خطأ: يجب أن يتساوى عدد نقاط x مع عدد قيم y.');
    end
    if length(unique(x_pts)) ~= n
        error('خطأ: يجب أن تكون جميع نقاط x متمايزة تماماً؛ تم تكرار نقطة مما يسبب قسمة على صفر.');
    end

    fprintf('\n=================================================================\n');
    fprintf('  استيفاء كثيرات حدود لاجرانج (Lagrange Interpolation)\n');
    fprintf('=================================================================\n');
    fprintf('النقاط المعطاة:\n');
    for i = 1:n
        fprintf('  النقطة %d: (x_%d = %.4f,  y_%d = %.4f)\n', i-1, i-1, x_pts(i), i-1, y_pts(i));
    end
    fprintf('النقطة المستهدفة للتقييم: x = %.4f\n', x_eval);
    fprintf('-----------------------------------------------------------------\n');

    L = ones(1, n);
    fprintf('\nحساب حدود لاجرانج الأساسية L_i(x) عند x = %.4f:\n', x_eval);

    for i = 1:n
        num_str = '';
        den_str = '';
        for j = 1:n
            if j ~= i
                term = (x_eval - x_pts(j)) / (x_pts(i) - x_pts(j));
                L(i) = L(i) * term;
            end
        end
        fprintf('  L_%d(%.2f) = %10.6f\n', i-1, x_eval, L(i));
    end

    % التجميع الكلي
    y_eval = sum(y_pts .* L);

    fprintf('-----------------------------------------------------------------\n');
    fprintf('✓ القيمة المستوفاة P_%d(%.4f) = %10.6f\n', n-1, x_eval, y_eval);
    fprintf('=================================================================\n');
end
