clc;
clear;
close all;

fprintf('=================================================================\n');
fprintf('   بدء تشغيل المنظومة الكاملة لخوارزميات التحليل العددي في MATLAB\n');
fprintf('=================================================================\n');

%% [1] طرق حل المعادلات غير الخطية (Root Finding)
fprintf('\n>>> [1] تجربة طريقة التنصيف (Bisection Method):\n');
bisection(@(x) x.^3 - x - 2, 1.0, 2.0, 1e-4, 50);

fprintf('\n>>> [2] تجربة طريقة الموضع الخاطئ (False Position Method):\n');
false_position(@(x) x.^3 - x - 2, 1.0, 2.0, 1e-4, 50);

fprintf('\n>>> [3] تجربة طريقة القاطع (Secant Method):\n');
secant(@(x) x.^3 - x - 2, 1.0, 2.0, 1e-4, 50);

fprintf('\n>>> [4] تجربة طريقة نيوتن رافسون (Newton-Raphson Method):\n');
newton_raphson(@(x) x.^3 - x - 2, @(x) 3*x.^2 - 1, 1.5, 1e-4, 50);

fprintf('\n>>> [5] تجربة طريقة النقطة الثابتة (Fixed Point Iteration):\n');
fixed_point(@(x) (x + 2).^(1/3), 1.5, 1e-4, 50);

%% [2] طرق حل الأنظمة الخطية (Linear Systems)
fprintf('\n>>> [6] تجربة طريقة حذف جاوس (Gaussian Elimination):\n');
A_gauss = [2, 1, -1; 3, 5, 2; 4, -1, -2];
b_gauss = [-1; 2; 1];
gauss_elimination(A_gauss, b_gauss);

fprintf('\n>>> [7] تجربة طريقة جاكوبي التكرارية (Jacobi Iteration):\n');
A_jacobi = [8, 1, 1; 3, 5, -1; 1, -1, 5];
b_jacobi = [26; 7; 7];
jacobi(A_jacobi, b_jacobi, [0; 0; 0], 1e-4, 50);

fprintf('\n>>> [8] تجربة قاعدة كرامر (Cramer''s Rule):\n');
A_cramer = [1, 2, 1; 2, 3, 4; 4, 3, 2];
b_cramer = [8; 20; 16];
cramer_rule(A_cramer, b_cramer);

fprintf('\n>>> [9] تجربة طريقة معكوس المصفوفة (Matrix Inversion):\n');
matrix_inversion(A_cramer, b_cramer);

%% [3] الاستيفاء والتفاضل والتكامل العددي
fprintf('\n>>> [10] تجربة استيفاء لاجرانج (Lagrange Interpolation):\n');
lagrange_interpolation([1, 2, 3], [1, 4, 9], 2.5);

fprintf('\n>>> [11] تجربة قاعدة شبه المنحرف المركبة (Trapezoidal Rule):\n');
trapezoidal_rule(@(x) 1 ./ (1 + x.^2), 0.0, 1.0, 4);

fprintf('\n>>> [12] تجربة صيغ التفاضل العددي (Numerical Differentiation):\n');
numerical_differentiation(@(x) sin(x), 1.0, 0.01);

fprintf('\n=================================================================\n');
fprintf('  🎉 تم بنجاح تشغيل جميع خوارزميات التحليل العددي الـ 12 بنسبة 100%%!\n');
fprintf('=================================================================\n');
