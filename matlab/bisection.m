function [root, T] = bisection(f, a, b, tol, max_iter)
% =========================================================================
% خوارزمية طريقة التنصيف (The Bisection Method)
% مادة: التحليل العددي (Numerical Analysis)
% =========================================================================
% الوظيفة:
%   إيجاد الجذر الحقيقي للمعادلة غير الخطية f(x) = 0 في الفترة [a, b]
%   بناءً على نظرية القيمة المتوسطة (Bolzano's Theorem).
%
% المدخلات (Inputs):
%   f        : دالة رياضية كـ function handle، مثال: @(x) x.^3 - x - 2
%   a        : بداية فترة الحصر (الحد الأدنى)
%   b        : نهاية فترة الحصر (الحد الأعلى)
%   tol      : الدقة المطلوبة للتوقف (افتراضياً: 1e-4)
%   max_iter : الحد الأقصى لعدد التكرارات (افتراضياً: 50)
%
% المخرجات (Outputs):
%   root     : القيمة التقريبية للجذر المحسوب
%   T        : جدول تفصيلي بجميع التكرارات وقيم الدوال والأخطاء
%
% مثال تشغيل تلقائي عند استدعاء الملف مباشرة بدون معاملات:
%   bisection
% =========================================================================

    % 1. القيم الافتراضية عند التشغيل المباشر كسكربت
    if nargin < 1 || isempty(f), f = @(x) x.^3 - x - 2; end
    if nargin < 2 || isempty(a), a = 1.0; end
    if nargin < 3 || isempty(b), b = 2.0; end
    if nargin < 4 || isempty(tol), tol = 1e-4; end
    if nargin < 5 || isempty(max_iter), max_iter = 50; end

    % إذا تم إدخال الدالة كنص string أو char، نحولها إلى function handle
    if ischar(f) || isstring(f)
        f = str2func(['@(x) ' char(f)]);
    end

    fprintf('\n=================================================================\n');
    fprintf('  طريقة التنصيف لحل المعادلات غير الخطية (Bisection Method)\n');
    fprintf('=================================================================\n');
    fprintf('الفترة الابتدائية: [%.4f, %.4f]\n', a, b);
    fprintf('الدقة المطلوبة (Tolerance): %e\n', tol);
    fprintf('أقصى عدد تكرارات: %d\n', max_iter);
    fprintf('-----------------------------------------------------------------\n');

    % 2. التحقق من صحة المدخلات
    if a >= b
        error('خطأ: يجب أن تكون بداية الفترة (a) أصغر من نهايتها (b).');
    end

    fa = f(a);
    fb = f(b);

    % فحص إذا كان أحد الطرفين جذراً مباشراً
    if abs(fa) < 1e-14
        root = a;
        fprintf('الجذر هو الحد a مباشرة: %.6f\n', root);
        return;
    end
    if abs(fb) < 1e-14
        root = b;
        fprintf('الجذر هو الحد b مباشرة: %.6f\n', root);
        return;
    end

    % شرط الحصر: f(a) * f(b) < 0
    if fa * fb > 0
        error('خطأ: شرط الحصر غير محقق! f(a)=%.4f و f(b)=%.4f لهما نفس الإشارة.\nيجب أن يكون f(a)*f(b) < 0.', fa, fb);
    end

    % 3. رأس جدول التكرارات
    fprintf('%-4s | %-9s | %-9s | %-9s | %-10s | %-10s | %-10s\n', ...
        'n', 'a', 'b', 'p (الجذر)', 'f(a)', 'f(p)', 'الخطأ (b-a)/2');
    fprintf('-----------------------------------------------------------------\n');

    table_data = [];
    p_prev = a;

    % 4. حلقة التكرار
    for n = 1:max_iter
        p = (a + b) / 2;
        fp = f(p);
        err = (b - a) / 2;

        fprintf('%-4d | %9.5f | %9.5f | %9.5f | %10.5f | %10.5f | %10.5e\n', ...
            n, a, b, p, fa, fp, err);

        table_data = [table_data; n, a, b, p, fa, fp, err]; %#ok<AGROW>

        % شرط التوقف: دقة الفترة أو القيمة الصفرية للدالة
        if err < tol || abs(fp) < 1e-12
            fprintf('-----------------------------------------------------------------\n');
            fprintf('✓ تم الوصول للحل بنجاح عند التكرار n = %d\n', n);
            fprintf('✓ الجذر التقريبي: x ≈ %.6f\n', p);
            fprintf('✓ قيمة الدالة عند الجذر: f(x) = %e\n', fp);
            fprintf('✓ الخطأ المتبقي: %e\n', err);
            root = p;
            T = table_data;
            return;
        end

        % تحديث الفترة بناءً على قاعدة الإشارات
        if fa * fp < 0
            b = p;
            fb = fp;
        else
            a = p;
            fa = fp;
        end
        p_prev = p;
    end

    root = p;
    T = table_data;
    warning('تم الوصول إلى الحد الأقصى للتكرارات (%d) دون الوصول للدقة المطلوبة تماماً.', max_iter);
end
