function [x, invA] = matrix_inversion(A, b)
% =========================================================================
% خوارزمية حل النظام الخطية بمعكوس المصفوفة (Matrix Inversion: X = A^-1 * B)
% مادة: التحليل العددي (Numerical Analysis)
% =========================================================================
% الوظيفة:
%   حل النظام الخطي: A * X = B
%   عن طريق إيجاد المعكوس A^{-1} = adj(A) / det(A)
%   ثم حساب متجه الحل: X = A^{-1} * B
%
% المدخلات (Inputs):
%   A : مصفوفة المعاملات المربعة (n x n)
%   b : متجه الثوابت (n x 1)
%
% المخرجات (Outputs):
%   x    : متجه الحل الناتج
%   invA : مصفوفة المعكوس A^{-1}
% =========================================================================

    if nargin < 1 || isempty(A)
        % مثال المقرر المعتمد
        A = [1, 2, 1; ...
             2, 3, 4; ...
             4, 3, 2];
    end
    if nargin < 2 || isempty(b)
        b = [8; 20; 16];
    end

    b = b(:);
    n = length(b);

    if size(A, 1) ~= size(A, 2) || size(A, 1) ~= n
        error('خطأ: يجب أن تكون المصفوفة A مربعة، ومتوافقة في الأبعاد مع المتجه b.');
    end

    fprintf('\n=================================================================\n');
    fprintf('  حل الأنظمة الخطية باستخدام معكوس المصفوفة (Matrix Inversion)\n');
    fprintf('=================================================================\n');

    % 1. فحص المحدد
    detA = det(A);
    fprintf('محدد المصفوفة det(A) = %.6f\n', detA);

    if abs(detA) < 1e-12
        error('خطأ: محدد المصفوفة يساوي صفراً؛ المصفوفة منفردة (Singular Matrix) ولا تمتلك معكوساً.');
    end

    % 2. حساب المعكوس
    invA = inv(A);
    fprintf('\nمصفوفة المعكوس A^(-1):\n');
    disp(invA);

    % 3. حساب متجه الحل X = A^(-1) * B
    x = invA * b;

    fprintf('عملية ضرب المعكوس في متجه الثوابت X = A^(-1) * B:\n');
    fprintf('-----------------------------------------------------------------\n');
    for i = 1:n
        row_expr = '';
        for j = 1:n
            if j > 1, row_expr = [row_expr, ' + ']; end %#ok<AGROW>
            row_expr = [row_expr, sprintf('(%.4f * %.2f)', invA(i, j), b(j))]; %#ok<AGROW>
        end
        fprintf('  x%d = %s = %10.6f\n', i, row_expr, x(i));
    end
    fprintf('-----------------------------------------------------------------\n');
    fprintf('✓ تم استخراج الحل بنجاح تام!\n');
end
